/**
 * Icon shown for a custom field: the picked one when it is a known icon,
 * otherwise the icon of the field type.
 */
export function resolveCustomFieldIcon(field: {
  icon?: string | null
  type: string
}): LucideIcon {
  if (isCustomFieldIconName(field.icon)) {
    return customFieldIconComponents[field.icon]
  }
  return customFieldIconsMap[field.type as CustomFieldType] ?? TextIcon
}
